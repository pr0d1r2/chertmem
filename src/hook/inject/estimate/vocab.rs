//! o200k's byte-pair merges over the part of its vocabulary compiled in
//! (src/hook T14, R8). o200k merges the adjacent pair whose token has
//! the lowest rank until no pair is a token. Over the tokens below a
//! rank only, the same merges happen until the first one needing a
//! token past it, then none: as many parts as o200k leaves, or more.
//! So a piece merges with the ranks below its cutoff, and the blob
//! holds every token below the cutoff of the pieces it can be part of:
//! all tokens of ref chars (refs count exactly), ASCII tokens below one
//! rank, the rest below a lower one (`estimate/vocab.bin`, generated by
//! a bpe test). Frequent pieces of 2 tokens or more are held with their
//! counts, so they skip merging.

#[cfg(test)]
mod tests;

pub(in crate::hook::inject) mod blob;

/// Ref chars: `:` and Crockford base32, as `chert:<ref>` writes them.
const REFS: &[u8] = b":0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/// Entries per front-coded block.
pub(in crate::hook::inject) const BLOCK: usize = 16;

/// Value bits under the shared length in a vocabulary entry's header.
pub(in crate::hook::inject) const RANK_BITS: u32 = 17;

/// Value bits under the shared length in a pieces entry's header.
pub(in crate::hook::inject) const PIECE_BITS: u32 = 8;

/// The narrowest class holding every byte of `token`: its cutoff, the
/// rank below which tokens of the class are kept, falls as classes
/// widen, so every token inside a piece is of a class with a cutoff at
/// least the piece's own (R8).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(in crate::hook::inject) enum Class {
    /// `:` and Crockford base32, as `chert:<ref>` writes them: every
    /// rank kept, so refs count exactly.
    Refs,
    /// ASCII.
    Ascii,
    /// ASCII, Latin-1 and the symbols from U+2000 to U+2FFF (dashes,
    /// arrows, maths): their UTF-8 bytes.
    Symbols,
    /// Anything.
    Other,
}

/// The class of `token`.
pub(in crate::hook::inject) fn class(token: &[u8]) -> Class {
    let symbol =
        |b: &u8| b.is_ascii() || matches!(b, 0x80..=0xbf | 0xc2 | 0xc3 | 0xe2);
    if token.iter().all(|b| REFS.contains(b)) {
        Class::Refs
    } else if token.is_ascii() {
        Class::Ascii
    } else if token.iter().all(symbol) {
        Class::Symbols
    } else {
        Class::Other
    }
}

/// The o200k tokens of `piece`, 1 o200k pre-split piece: never fewer
/// than o200k's. RED: lookups only, a piece not found counts bytes.
pub(super) fn count(piece: &[u8]) -> usize {
    let cut = blob::cutoff(piece);
    if piece.len() < 2 || blob::rank(piece, cut).is_some() {
        return piece.len().min(1);
    }
    blob::known(piece).unwrap_or(piece.len())
}
