use super::{render, targets};
use crate::baseline::Row;
use std::collections::BTreeMap;

type Res = Result<(), Box<dyn std::error::Error>>;

const SPEC: &str = "# SPEC\n\n## \u{a7}C CONSTRAINTS\n\n- latency targets \
    (D20), benchmark-gated: hook write < 5 ms \u{b7} `get_observations` < 2 \
    ms.\n- other: x\n";

fn row(suite: &str, fixture: &str, median_ms: f64, target: &str) -> Row {
    Row {
        suite: suite.to_owned(),
        fixture: fixture.to_owned(),
        target: (target != "-").then(|| target.to_owned()),
        median_ms,
        p95_ms: median_ms * 2.0,
        tolerance: 0.5,
        machine: "Test CPU".to_owned(),
        os: "TestOS 1.0".to_owned(),
        date: "2026-10-25".to_owned(),
        recount: format!("cargo bench -- '^{suite}/{fixture}$'"),
    }
}

#[test]
fn targets_are_read_from_the_root_c_line() -> Res {
    let got = targets(SPEC)?;
    let want = BTreeMap::from([
        ("get_observations".to_owned(), 2.0),
        ("hook write".to_owned(), 5.0),
    ]);
    assert_eq!(got, want);
    assert!(targets("# SPEC\n").is_err());
    assert!(targets("- latency targets none").is_err());
    let bad = targets("- latency targets: hook write under 5 ms");
    assert!(bad.is_err_and(|e| e.contains("hook write under 5 ms")));
    Ok(())
}

fn page() -> Result<String, String> {
    let rows = [
        row("get_observations", "1k-p52", 0.08, "get_observations"),
        row("get_observations", "1M-p52", 2.5, "get_observations"),
        row("partition_scan", "1k-p52", 0.5, "-"),
    ];
    let page = render(&rows, &targets(SPEC)?)?;
    assert_eq!(render(&rows, &targets(SPEC)?)?, page, "deterministic");
    Ok(page)
}

#[test]
fn every_row_shows_median_p95_target_and_pass() -> Res {
    let page = page()?;
    assert!(page.starts_with("# Performance\n\n<!-- Generated by"));
    let head =
        "\n## get_observations\n\nTarget: get_observations under 2 ms.\n";
    assert!(page.contains(head));
    for line in [
        "| 1k-p52 | 0.08000 ms | 0.1600 ms | 2 ms | yes |",
        "| 1M-p52 | 2.500 ms | 5.000 ms | 2 ms | no |",
        "| 1k-p52 | 0.5000 ms | 1.000 ms | - | - |",
    ] {
        assert!(page.contains(&format!("\n{line}\n")), "{line}");
    }
    Ok(())
}

#[test]
fn every_row_has_its_recount_and_a_suite_may_have_no_target() -> Res {
    let page = page()?;
    assert!(page.contains("No latency target; measured for scale."));
    let recount = "- 1M-p52: `cargo bench -- '^get_observations/1M-p52$'`\n";
    assert!(page.contains(recount));
    Ok(())
}

#[test]
fn each_run_is_named_by_date_and_machine() -> Res {
    let mut other = row("s", "10k-p52", 1.0, "-");
    other.date = "2026-10-26".to_owned();
    let rows = [
        row("s", "1k-p52", 1.0, "-"),
        other,
        row("s", "1M-p", 1.0, "-"),
    ];
    let page = render(&rows, &BTreeMap::new())?;
    let a = "\nMeasured 2026-10-25 on Test CPU, TestOS 1.0: 1k-p52, 1M-p.\n";
    assert!(page.contains(a), "{page}");
    let b = "\nMeasured 2026-10-26 on Test CPU, TestOS 1.0: 10k-p52.\n";
    assert!(page.contains(b), "{page}");
    Ok(())
}

#[test]
fn a_target_missing_from_the_spec_is_an_error() {
    let rows = [row("s", "1k-p52", 1.0, "semantic re-rank")];
    let err = render(&rows, &BTreeMap::new()).err().unwrap_or_default();
    assert_eq!(err, "s: target `semantic re-rank` is not in SPEC.md C");
}
